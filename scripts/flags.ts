/**
 * Content QUALITY FLAGS for review (R4) — heuristics that point at items worth inspecting, NOT proof of defects.
 *   pnpm content:flags   → reports/flags.md   (needs source/pages for the number check)
 *
 *  length-cue      single choice whose correct option is > 1.3× longer than every distractor (guessable)
 *  number          a number (≥ 2 digits or decimal) in an explanation / answer / correct option / key point that does
 *                  not occur on the cited pages ±1 (course & disputed points; supplementary points are beyond the script)
 *  disputed-mcq    a choice question on a course-disputed point whose prompt does not say "podle skript"
 *  near-duplicate  two exercises of different points with very similar wording (token Jaccard ≥ 0.5)
 *  recognition-only a tier-A point whose exercises are all multiple choice
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { loadContentFiles, normalizeForMatch, bundle } from "../src/content/validate";
import type { PointWithTopic, Exercise } from "../src/content/schema";

const { criteria, topics } = loadContentFiles();
const b = bundle(criteria, topics);
const fileOf = new Map(topics.flatMap((t) => t.data.points.map((p) => [p.id, t.file] as const)));
type Flag = { kind: string; file: string; id: string; detail: string };
const flags: Flag[] = [];
const add = (kind: string, p: PointWithTopic, ex: Exercise | null, detail: string) =>
  flags.push({ kind, file: fileOf.get(p.id) ?? "?", id: ex ? `${p.id}/${ex.id}` : p.id, detail });

// --- pages for the number check
const pageCache = new Map<number, string>();
const page = (n: number) => {
  if (!pageCache.has(n)) {
    const f = join("source/pages", `${String(n).padStart(3, "0")}.txt`);
    pageCache.set(n, existsSync(f) ? normalizeForMatch(readFileSync(f, "utf8")).replace(/(\d)\s+(\d{3})\b/g, "$1$2") : "");
  }
  return pageCache.get(n)!;
};
const haveSource = existsSync("source/pages");
const numbersIn = (t: string) => (t.match(/\d+(?:[.,]\d+)?/g) ?? []).filter((x) => x.length >= 2 || /[.,]/.test(x));
const textsOf = (p: PointWithTopic): string[] => {
  const out = [p.explanation];
  for (const e of p.exercises) {
    if (e.type === "reveal") out.push(e.answer);
    if (e.type === "choice") out.push(...e.options.filter((o) => o.correct).map((o) => o.text));
    if (e.type === "explain") out.push(e.modelAnswer, ...e.keyPoints);
  }
  return out;
};
const tokens = (s: string) => new Set(s.normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().match(/[a-z0-9]{4,}/g) ?? []);

for (const p of b.points) {
  // recognition-only
  if (p.tier === "A" && p.exercises.every((e) => e.type === "choice")) add("recognition-only", p, null, "tier A, only multiple choice");
  for (const e of p.exercises) {
    if (e.type !== "choice") continue;
    // length cue
    if (!e.multiple) {
      const c = e.options.find((o) => o.correct)!.text.length;
      const others = e.options.filter((o) => !o.correct).map((o) => o.text.length);
      if (c > 15 && c > 1.3 * Math.max(...others)) add("length-cue", p, e, `correct ${c} chars vs longest distractor ${Math.max(...others)}`);
    }
    // disputed MCQ without "podle skript"
    if (p.status === "course-disputed" && !/podle skript|ve skriptech|skripta/i.test(e.prompt)) add("disputed-mcq", p, e, e.prompt.slice(0, 90));
  }
  // numbers not on the cited pages (±1)
  if (haveSource && p.status !== "supplementary") {
    const pages = [...new Set(p.source.pages.flatMap((n) => [n - 1, n, n + 1]))].map(page).join(" ");
    const missing = [...new Set(textsOf(p).flatMap(numbersIn))].filter((x) => {
      const a = x.replace(".", ",");
      const b2 = x.replace(",", ".");
      return !pages.includes(a) && !pages.includes(b2);
    });
    if (missing.length) add("number", p, null, `not on pages ${p.source.pages.join(", ")} (±1): ${missing.join(", ")}`);
  }
}
// near-duplicates across points
const items = b.points.flatMap((p) =>
  p.exercises.filter((e) => e.type !== "case").map((e) => ({ p, e, t: tokens(`${e.prompt} ${e.type === "choice" ? e.options.filter((o) => o.correct).map((o) => o.text).join(" ") : ""}`) })),
);
for (let i = 0; i < items.length; i++)
  for (let j = i + 1; j < items.length; j++) {
    if (items[i].p.id === items[j].p.id) continue;
    const [a, c] = [items[i].t, items[j].t];
    let x = 0;
    for (const w of a) if (c.has(w)) x++;
    const jac = x / (a.size + c.size - x || 1);
    if (jac >= 0.5) add("near-duplicate", items[i].p, items[i].e, `~ ${items[j].p.id}/${items[j].e.id} (${jac.toFixed(2)})`);
  }

const kinds = ["length-cue", "number", "disputed-mcq", "near-duplicate", "recognition-only"];
const lines = [
  "# Content quality flags",
  "",
  "_Generated by `pnpm content:flags` — heuristics for INSPECTION, not proof of defects. Do not edit._",
  "",
  ...kinds.map((k) => `- **${k}**: ${flags.filter((f) => f.kind === k).length}`),
  "",
];
for (const file of [...new Set(flags.map((f) => f.file))].sort()) {
  lines.push(`## ${file}`, "");
  for (const f of flags.filter((x) => x.file === file).sort((a, c) => a.kind.localeCompare(c.kind))) lines.push(`- \`${f.kind}\` ${f.id} — ${f.detail}`);
  lines.push("");
}
writeFileSync("reports/flags.md", lines.join("\n"));
console.log(kinds.map((k) => `${k}: ${flags.filter((f) => f.kind === k).length}`).join(" · "), haveSource ? "" : "(number check skipped: no source/pages)");
